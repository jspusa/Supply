import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { publicCatalogSnapshot } from '../catalog/catalog-change-plan.js';

const supplyRepo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const defaultFbaRepo = path.resolve(supplyRepo, '..', 'FBA');
const runtimeFiles = Object.freeze([
  {
    source:'catalog/product-catalog.js',
    output:'catalog-update-product-catalog.mjs',
    transform:value => value,
  },
  {
    source:'catalog/product-catalog-release.js',
    output:'catalog-update-release.mjs',
    transform:value => value,
  },
  {
    source:'catalog/raw-product-catalog-overlay.js',
    output:'catalog-update-overlay.mjs',
    transform:value => value.replace("from './product-catalog.js';", "from './catalog-update-product-catalog.mjs';"),
  },
  {
    source:'catalog/catalog-change-plan.js',
    output:'catalog-update-change-plan.mjs',
    transform:value => value
      .replace("from './product-catalog-release.js';", "from './catalog-update-release.mjs';")
      .replace("from './product-catalog.js';", "from './catalog-update-product-catalog.mjs';"),
  },
]);

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function stableJson(value) {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(',')}]`;
  if (!value || typeof value !== 'object') return JSON.stringify(value);
  return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${stableJson(value[key])}`).join(',')}}`;
}

function baselineSource(catalog) {
  return `/* Generated by jspusa/Supply. Do not edit in either site. */\n(function installCatalogUpdateBaseline(root) {\n  root.JSPCatalogUpdateBaseline = ${JSON.stringify(catalog)};\n})(typeof globalThis === 'object' ? globalThis : this);\n`;
}

function outputs({ catalogPath, fbaRepo }) {
  const fullCatalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
  const catalog = publicCatalogSnapshot(fullCatalog);
  const generated = new Map();
  generated.set('catalog-update-baseline.js', baselineSource(catalog));
  generated.set('catalog-update-planner.mjs', fs.readFileSync(path.join(supplyRepo, 'shared', 'catalog-update-planner.mjs'), 'utf8'));
  for (const file of runtimeFiles) {
    generated.set(file.output, file.transform(fs.readFileSync(path.join(supplyRepo, file.source), 'utf8')));
  }
  const lock = {
    schemaVersion:1,
    canonicalOwner:'jspusa/Supply',
    catalogVersion:catalog.catalogVersion,
    catalogSha256:sha256(stableJson(catalog)),
    files:Object.fromEntries([...generated].map(([name, value]) => [name, sha256(value)])),
  };
  generated.set('catalog-update-runtime-lock.json', `${JSON.stringify(lock, null, 2)}\n`);
  const targets = [path.join(supplyRepo, 'shared')];
  if (fbaRepo && fs.existsSync(path.join(fbaRepo, 'package.json'))) targets.push(fbaRepo);
  return { generated, targets };
}

function writeOrCheck(generated, targets, check) {
  const stale = [];
  for (const target of targets) {
    for (const [name, value] of generated) {
      const output = path.join(target, name);
      if (check) {
        if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== value) stale.push(output);
      } else {
        fs.mkdirSync(path.dirname(output), { recursive:true });
        fs.writeFileSync(output, value);
      }
    }
  }
  if (stale.length) throw new Error(`Catalog Update runtime projection is stale:\n- ${stale.join('\n- ')}`);
}

export function writeCatalogUpdateRuntime({
  catalogPath = path.join(supplyRepo, 'catalog', 'product-catalog.json'),
  fbaRepo = defaultFbaRepo,
  check = false,
} = {}) {
  const result = outputs({ catalogPath:path.resolve(catalogPath), fbaRepo:path.resolve(fbaRepo) });
  writeOrCheck(result.generated, result.targets, check);
  return {
    targets:result.targets,
    files:[...result.generated.keys()],
  };
}

function option(name) {
  const index = process.argv.indexOf(name);
  if (index < 0) return null;
  const value = process.argv[index + 1];
  if (!value || value.startsWith('--')) throw new Error(`${name} requires a value`);
  return value;
}

function main() {
  const result = writeCatalogUpdateRuntime({
    catalogPath:option('--catalog') || undefined,
    fbaRepo:option('--fba-repo') || undefined,
    check:process.argv.includes('--check'),
  });
  console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} Catalog Update runtime (${result.files.length} files) for ${result.targets.length} site(s)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try { main(); }
  catch (error) { console.error(error?.stack || error); process.exitCode = 1; }
}
